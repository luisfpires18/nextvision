#!/usr/bin/env node
/**
 * build-redirects.mjs — `public/_redirects`, generated from the route map.
 *
 * PHASE 11. `src/data/routes.json` has held the redirect table since Phase 0.5 and
 * nothing ever emitted it, so `/blog` — linked from the "Ver Tudo" button on all twenty
 * project pages — has stayed a 404 through every build (audit §9.6, ROUTE_MIGRATION §3).
 * This closes that.
 *
 * ── Why a file rather than Astro's `redirects` config ────────────────────────
 * With `output: 'static'`, Astro's own `redirects` are emitted as HTML documents carrying
 * a meta refresh. Each one is a real page: it gets a URL, a canonical, and a place in the
 * crawl — which is the opposite of what a 301 is for. `_redirects` is resolved by the host
 * before any document exists, so `/blog` answers with a status code and no body.
 *
 * ── What is NOT here, and why ────────────────────────────────────────────────
 *   /en/ -> /            The English homepage EXISTS now, so the Phase 0.5 line that sent
 *                        it to Portuguese is retired rather than emitted. Redirecting a
 *                        real page to another language would undo the whole locale.
 *   /wp-content/uploads  Those targets are R2 keys and R2 is not provisioned. Emitting
 *                        them now would point 77 URLs at a host that does not answer.
 *   the 410 patterns     `_redirects` speaks only in 3xx. `/wp-json/*` and friends need a
 *                        Worker or a Function to return 410, which is the deployment
 *                        phase's job. They 404 until then, which is wrong but not
 *                        harmful, and it is recorded rather than quietly dropped.
 *
 * Both omissions are listed in the generated file itself, so the gap is visible to
 * whoever opens it rather than only to whoever reads this script.
 */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'public', '_redirects');

const routes = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/routes.json'), 'utf8'));

/**
 * Retired because the destination now exists in its own right.
 *
 * The map's `/en/ -> /` line was written when English was empty and says so in its own
 * `reason` field: "until then /en/ itself redirects to /". English is real now, so that
 * line must not be emitted — redirecting the English homepage to the Portuguese one would
 * undo the locale. `/en/homepage-english/` still redirects, and now lands on a page that
 * exists.
 *
 * Kept as a filter rather than by editing routes.json, because that file is generated
 * from the preservation archive and describes what the LIVE site does.
 */
const RETIRED = new Set(['/en/']);

const lines = [
  '# GENERATED by scripts/build-redirects.mjs — do not edit by hand.',
  '# Source of truth: src/data/routes.json (docs/ROUTE_MIGRATION.md §3).',
  '#',
  '# Cloudflare Workers Static Assets reads this file before the Worker runs, so these',
  '# answer with a status code and no body — unlike a meta-refresh page, which would be',
  '# crawlable. Every rule is exactly 2 or 3 whitespace-separated tokens; a comment is a',
  '# whole line of its own, because a trailing one is a deploy-time API error (see below).',
  '',
];

let count = 0;
for (const r of routes.redirects) {
  if (RETIRED.has(r.from)) continue;
  // A NOTE GOES ON ITS OWN LINE, NEVER AFTER THE RULE. Cloudflare Pages tolerated a
  // trailing `# comment`; Workers Static Assets does not, and the check runs server-side
  // at deploy time rather than at build time:
  //     Invalid _redirects configuration:
  //     Line 7: Expected exactly 2 or 3 whitespace-separated tokens. Got 8. [code: 100324]
  // Miniflare's local parser accepted the same line and reported "6 valid redirect rules",
  // so `wrangler dev` cannot catch this and only a real deploy can. Found that way.
  if (r.confidence === 'assumed') lines.push('# ASSUMED — decision D5');
  lines.push(`${r.from}    ${r.to}    ${r.status}`);
  count += 1;
}

lines.push(
  '',
  '# Trailing slash is NOT a rule here. `build.format: directory` writes every route as',
  '# <route>/index.html, and the asset handler resolves /sobre to /sobre/ against that',
  '# directory on its own. A hand-written splat rule for it is the classic way to build a',
  '# redirect loop, and it would be solving a problem the host has already solved.',
  '',
  '# ─────────────────────────────────────────────────────────────────────────────',
  '# NOT EMITTED YET, and both are deliberate:',
  '#',
  `#   /wp-content/uploads/*   ${routes.uploads.length} mapped URLs whose targets are R2 keys.`,
  '#                           R2 is not provisioned, so emitting them would point every',
  '#                           inbound hotlink and cached og:image at a host that does not',
  '#                           answer. Regenerate this file after the R2 phase.',
  '#',
  '#   /wp-json/*, /wp-admin/*, /wp-includes/*, /xmlrpc.php, /feed/, /comments/feed/',
  '#                           These should be 410 Gone. _redirects speaks only in 3xx;',
  '#                           a Worker or Function returns the right status, and that is',
  '#                           the deployment phase. They 404 until then.',
);

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `${lines.join('\n')}\n`, 'utf8');
console.log(`  ok    public/_redirects — ${count} redirects emitted`);
