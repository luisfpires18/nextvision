/** Smash/ has moved before. Look, don't assume. */
export function findSmash() {
  for (const c of SMASH_CANDIDATES) if (existsSync(c)) return c;
  return null;
}

/* ══════════════════════════════════════════════════════════ encoder policy ══ */

/**
 * Named once, hashed into every derivative's cache fingerprint. Change a number here and
 * media:build re-encodes exactly the files that number affects — nothing else.
 */
export const ENCODER = {
  /** Stills. WebP is the baseline every browser we support decodes. */
  webpQuality: 76,
  /**
   * AVIF, offered alongside. Measured on this project's own frames: ~43% smaller than the
   * WebP at visually identical quality. `-still-picture 1` is what makes it an image
   * rather than a one-frame video, and cpu-used 6 keeps a 200-file build under two
   * minutes.
   */
  avifCrf: 32,
  avifCpuUsed: 6,
  /** Loops are decorative and muted; CRF can be modest. Nothing here is the film itself. */
  crf: 30,
  /**
   * VP9, for hero-class clips only. It is ~25% smaller than the H.264 beside it, and a
   * hero autoplays before the reader has done anything — that saving is real. A hover
   * preview does not autoplay, so a second encode of it would be storage nobody
   * downloads. `where useful` means above the fold.
   */
  vp9Crf: 36,
  vp9CpuUsed: 2,
  version: 2,
};

/** Cache-Control per class of object. Hashed names mean the long one is safe. */
export const CACHE_IMMUTABLE = 'public, max-age=31536000, immutable';

export const CONTENT_TYPES = {
  webp: 'image/webp',
  avif: 'image/avif',
  mp4: 'video/mp4',
  webm: 'video/webm',
  jpg: 'image/jpeg',
  png: 'image/png',
};

/* ═════════════════════════════════════════════════════════════════ ffmpeg ══ */

export async function ffmpeg(args) {
  await exec('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...args], {
    maxBuffer: 32 * 1024 * 1024,
  });
}

export async function probeSize(file) {
  const { stdout } = await exec('ffprobe', [
    '-v', 'error', '-select_streams', 'v:0',
    '-show_entries', 'stream=width,height', '-of', 'csv=p=0:s=x', file,
  ]);
  const [w, h] = stdout.trim().split('x').map(Number);
  return { width: w, height: h };
}

/** Everything media:inspect needs to describe an unknown source file. */
export async function probeFull(file) {
  const { stdout } = await exec('ffprobe', [
    '-v', 'error', '-show_entries',
    'stream=codec_type,codec_name,width,height,r_frame_rate,bit_rate:format=duration,bit_rate,size',
    '-of', 'json', file,
  ], { maxBuffer: 8 * 1024 * 1024 });
  return JSON.parse(stdout);
}

/** Resolve an accented filename across NFC/NFD normalisation (macOS vs Windows). */
export async function resolveSource(dir, name) {
  const files = await fs.readdir(dir);
  const hit = files.find((f) => f.normalize('NFC') === name.normalize('NFC'));
  return hit ? path.join(dir, hit) : null;
}

export const filterFor = (crop, width) =>
  [crop ? `crop=${crop}` : null, `scale=${width}:-2:flags=lanczos`].filter(Boolean).join(',');

/* ═══════════════════════════════════════════════════════════════── hashing ══ */

export async function hashFile(file) {
  const h = crypto.createHash('sha256');
  h.update(await fs.readFile(file));
  return h.digest('hex');
}

export const shortHash = (sha256) => sha256.slice(0, 8);

export const fingerprint = (obj) =>
  crypto.createHash('sha256').update(JSON.stringify(obj)).digest('hex').slice(0, 16);

/** Source identity without reading gigabytes: path, size, mtime. */
export async function sourceStamp(file) {
  const s = await fs.stat(file);
  return { file: path.relative(ROOT, file).replace(/\\/g, '/'), size: s.size, mtimeMs: Math.round(s.mtimeMs) };
}

export const bytesOf = async (p) => { try { return (await fs.stat(p)).size; } catch { return 0; } };

/* ══════════════════════════════════════════════════════════ object naming ══ */

/**
 * The one place an object key is assembled.
 *
 * `projects/leonor/hero` + 1140 + `mp4` + hash → `projects/leonor/hero/1140.a1b2c3d4.mp4`
 *
 * The manifest key is the directory and the rendition is the leaf, so every derivative of
 * one asset sits together in the bucket and `projects/{slug}/` lists a project's whole
 * footprint. Nothing outside this function may build a path.
 */
export const objectPath = (key, width, ext, sha) => `${key}/${width}.${shortHash(sha)}.${ext}`;

export const mirrorPath = (objPath) => path.join(MIRROR, objPath);

/* ═════════════════════════════════════════════════════════════ mirror i/o ══ */

/**
 * Encode into a scratch file, hash it, then move it to its content-addressed name.
 *
 * Doing it in that order is what makes the hash trustworthy: the name is derived from the
 * bytes that exist, never from the inputs we believe produced them.
 */
export async function emit(key, width, ext, encode) {
  const tmp = path.join(MIRROR, '.tmp', `${key.replace(/\//g, '_')}-${width}.${ext}`);
  await fs.mkdir(path.dirname(tmp), { recursive: true });
  await encode(tmp);

  const sha = await hashFile(tmp);
  const objPath = objectPath(key, width, ext, sha);
  const dest = mirrorPath(objPath);
  await fs.mkdir(path.dirname(dest), { recursive: true });
  await fs.rename(tmp, dest);

  const size = await probeSize(dest);
  return {
    path: objPath,
    sha256: sha,
    width: size.width,
    height: size.height,
    bytes: await bytesOf(dest),
    contentType: CONTENT_TYPES[ext],
  };
}

export async function readJson(file, fallback) {
  try { return JSON.parse(await fs.readFile(file, 'utf8')); } catch { return fallback; }
}

export async function writeJson(file, value) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

/** Every file currently in the mirror, as bucket-relative object paths. */
export async function listMirror(dir = MIRROR, prefix = '') {
  const out = [];
  let entries;
  try { entries = await fs.readdir(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    if (e.name === '.tmp') continue;
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...await listMirror(path.join(dir, e.name), rel));
    else out.push(rel);
  }
  return out;
}

export const human = (bytes) =>
  bytes >= 1048576 ? `${(bytes / 1048576).toFixed(2)} MB` : `${(bytes / 1024).toFixed(0)} KB`;
