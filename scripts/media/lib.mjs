/**
 * lib.mjs — the encoder and the naming rules. Shared by media:build, media:sync,
 * media:verify and media:inspect.
 *
 * Two ideas carry the whole pipeline:
 *
 *   1. EVERY delivered file is content-addressed. Its name ends in eight hex characters
 *      of its own SHA-256, so two files with the same name are the same bytes. That makes
 *      the CDN cache immutable (no purge, ever), and it makes sync a set difference
 *      rather than a checksum comparison: if the key is there, the bytes are there.
 *
 *   2. The local mirror is BYTE-IDENTICAL to the bucket, at the same relative paths.
 *      `media/dist/projects/leonor/hero/1140.a1b2c3d4.mp4` uploads to
 *      `projects/leonor/hero/1140.a1b2c3d4.mp4`. Switching between them is one base URL,
 *      which is why local development needs no network and no credentials.
 */

