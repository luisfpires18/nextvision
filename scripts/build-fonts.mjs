#!/usr/bin/env node
/**
 * build-fonts.mjs — TTF → subsetted WOFF2.
 *
 * Reads the owner-supplied originals in source-assets/fonts/ and writes web fonts to
 * public/__generated/fonts/ (gitignored). **Source TTFs are never modified.**
 *
 * Deliberately minimal: only the faces the concepts actually use. The full 40-file
 * set stays in source-assets/ so adding a weight later is one line here.
 *
 * Typography is PROVISIONAL (CLAUDE.md §4). If Tatiana changes the families, this
 * script takes a different input list and the --font-* tokens change; no component
 * changes.
 *
 * Requires: python -m pip install "fonttools[woff]" brotli
 */

import fs from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const exec = promisify(execFile);
const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'source-assets', 'fonts');
const OUT = path.join(ROOT, 'public', '__generated', 'fonts');

/**
 * Faces to ship. `weight` is the REAL usWeightClass read from the binaries in session 2 —
 * Barlow's Thin is 250 and ExtraLight is 275, not the usual 100/200 (docs/PROJECT_CONTEXT
 * §7.1). Declaring the wrong value makes browsers synthesise the wrong face.
 */
const FACES = [
  { file: 'Barlow/Barlow-Regular.ttf', family: 'Barlow', weight: 400, style: 'normal', out: 'barlow-400' },
  { file: 'Barlow/Barlow-Medium.ttf', family: 'Barlow', weight: 500, style: 'normal', out: 'barlow-500' },
  { file: 'Barlow/Barlow-SemiBold.ttf', family: 'Barlow', weight: 600, style: 'normal', out: 'barlow-600' },
  // Design v2 (Tatiana): Light carries the rail and spine labels, Black every display line.
  { file: 'Barlow_Condensed/BarlowCondensed-Light.ttf', family: 'Barlow Condensed', weight: 300, style: 'normal', out: 'barlow-condensed-300' },
  { file: 'Barlow_Condensed/BarlowCondensed-Medium.ttf', family: 'Barlow Condensed', weight: 500, style: 'normal', out: 'barlow-condensed-500' },
  { file: 'Barlow_Condensed/BarlowCondensed-Bold.ttf', family: 'Barlow Condensed', weight: 700, style: 'normal', out: 'barlow-condensed-700' },
  { file: 'Barlow_Condensed/BarlowCondensed-Black.ttf', family: 'Barlow Condensed', weight: 900, style: 'normal', out: 'barlow-condensed-900' },
  { file: 'Space_Mono/SpaceMono-Regular.ttf', family: 'Space Mono', weight: 400, style: 'normal', out: 'space-mono-400' },
];

/**
 * Subset: Latin + Latin-1 Supplement + Latin Extended-A, plus the punctuation the
 * site actually uses. Portuguese needs á à â ã é ê í ó ô õ ú ü ç and their capitals —
 * all inside Latin-1 Supplement — plus curly quotes, en/em dash, ellipsis, º, ª, «».
 */
const UNICODES = [
  'U+0000-00FF', // Basic Latin + Latin-1 Supplement (all Portuguese diacritics)
  'U+0100-017F', // Latin Extended-A (for European names in credits)
  'U+2010-2027', // hyphens, dashes, quotes, ellipsis
  'U+2030-205E', // ‰ ‹ › and misc punctuation
  'U+20AC',      // €
  'U+2122',      // ™
  'U+00AA,U+00BA', // ª º — used in Portuguese ordinals
].join(',');

const PYFTSUBSET = ['-m', 'fontTools.subset'];

async function main() {
  await fs.mkdir(OUT, { recursive: true });
  const report = [];

  for (const face of FACES) {
    const src = path.join(SRC, face.file);
    if (!existsSync(src)) { console.log(`  !! missing source: ${face.file}`); continue; }
    const dest = path.join(OUT, `${face.out}.woff2`);

    await exec('python', [
      ...PYFTSUBSET, src,
      `--unicodes=${UNICODES}`,
      '--layout-features=kern,liga,calt,tnum,onum,ccmp,mark,mkmk',
      '--flavor=woff2',
      '--desubroutinize',
      '--no-hinting',
      `--output-file=${dest}`,
    ], { maxBuffer: 16 * 1024 * 1024 });

    const before = (await fs.stat(src)).size;
    const after = (await fs.stat(dest)).size;
    report.push({ ...face, before, after });
    console.log(`  ${face.out.padEnd(22)} ${(before / 1024).toFixed(0).padStart(4)} KB → ${(after / 1024).toFixed(1).padStart(6)} KB woff2`);
  }

  const total = report.reduce((s, r) => s + r.after, 0);
  console.log(`\n  ${report.length} faces, ${(total / 1024).toFixed(1)} KB total`);

  // Emit the @font-face block, so the declared weights can never drift from the binaries.
  const css = `/**
 * Generated by scripts/build-fonts.mjs — DO NOT EDIT.
 * Subsetted from the owner-supplied TTFs in source-assets/fonts/ (never modified).
 *
 * Weights are the REAL usWeightClass values read from the binaries. Typography is
 * PROVISIONAL (CLAUDE.md §4): swapping families means re-running this script and
 * changing the --font-* tokens. No component changes.
 */
${report.map((r) => `@font-face {
  font-family: '${r.family}';
  src: url('/__generated/fonts/${r.out}.woff2') format('woff2');
  font-weight: ${r.weight};
  font-style: ${r.style};
  font-display: swap;
}`).join('\n')}
`;
  await fs.writeFile(path.join(ROOT, 'src', 'styles', 'fonts.css'), css);
  console.log('  wrote src/styles/fonts.css');
}

main().catch((e) => { console.error(e.stderr ?? e); process.exit(1); });
